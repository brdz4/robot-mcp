def write_marker(pid: int) -> None:
    with open(rc._INTERACTIVE_MARKER, "w", encoding="utf-8") as marker:
        marker.write(str(pid))


def test_marker() -> None:
    if os.path.exists(rc._INTERACTIVE_MARKER):
        sys.exit("Hay un marcador de modo no interactivo activo: algún servidor está escribiendo. Reintenta luego.")
    app = type("App", (), {"Interactive": 0})()
    write_marker(os.getppid())  # proceso vivo = otro servidor escribiendo
    rc._repair_interactive(app)
    assert app.Interactive == 0 and os.path.exists(rc._INTERACTIVE_MARKER), "no debe tocar Robot si el dueño vive"
    write_marker(2**31 - 1)  # proceso inexistente = servidor muerto a mitad
    rc._repair_interactive(app)
    assert app.Interactive == 1 and not os.path.exists(rc._INTERACTIVE_MARKER), "debe reparar si el dueño murió"
    write_marker(os.getppid())  # otro chat escribiendo: una segunda escritura se rechaza sin tocar Robot
    try:
        with rc.non_interactive(app):
            raise AssertionError("debía rechazar la escritura concurrente")
    except ToolError as exc:
        assert "Otro chat" in str(exc) and app.Interactive == 1, exc
    os.remove(rc._INTERACTIVE_MARKER)
    with rc.non_interactive(app):  # sin nadie más: apaga la interacción y la restaura al salir
        assert app.Interactive == 0 and os.path.exists(rc._INTERACTIVE_MARKER)
    assert app.Interactive == 1 and not os.path.exists(rc._INTERACTIVE_MARKER), "debe restaurar al salir"


async def test_busy() -> None:
    rc._run = lambda fn, need_project: time.sleep(1.5) or "ok"
    try:
        await rc.on_robot(lambda s: None, timeout=0.3)
        raise AssertionError("debía vencer el plazo")
    except ToolError as exc:
        assert "sigue en curso" in str(exc), exc
    try:
        await rc.on_robot(lambda s: None, timeout=5)
        raise AssertionError("debía rechazar mientras el hilo sigue ocupado")
    except ToolError as exc:
        assert "ocupado" in str(exc), exc
    await asyncio.sleep(1.5)
    assert await rc.on_robot(lambda s: None, timeout=5) == "ok", "al terminar debe volver a aceptar llamadas"


def test_strict_cases() -> None:
    kind = type("Kind", (), {"ToString": lambda self: "I_CAT_STATIC_LINEAR"})()
    case = type("Case", (), {"Name": "c", "AnalizeType": kind})()
    cases = type("Cases", (), {"Exist": lambda self, n: n in (1, 2), "Get": lambda self, n: case})()
    session = type("S", (), {"structure": type("St", (), {"Cases": cases})()})()
    assert [c["number"] for c in results._cases(session, "1 2 3")] == [1, 2], "sin strict omite los que faltan"
    try:
        results._cases(session, "1 3", strict=True)
        raise AssertionError("strict debía fallar")
    except ToolError as exc:
        assert "[3]" in str(exc), exc


def test_generated_records() -> None:
    flags = [True, True, False, True, False]  # reparto de paneles + cargas del usuario
    records = type("Recs", (), {"Count": len(flags), "Get": lambda self, i: flags[i - 1]})()
    om = type("Om", (), {"IRobotLoadRecordCommon": staticmethod(lambda flag: type("C", (), {"IsAutoGenerated": flag})())})()
    assert rc.generated_records(om, records) == {1, 2, 4}, "deben salir solo los generados por Robot"


def test_nec_combinations() -> None:
    combos = writes.nec_combinations([1], [2], [], [], [7], [10])
    got = {c.name: {f.case: f.factor for f in c.factors} for c in combos}
    assert got["NEC1 1.4D"] == {1: 1.4} and got["NEC2 1.2D+1.6L"] == {1: 1.2, 2: 1.6}, got
    assert got["NEC4 1.2D-E7+L"] == {1: 1.2, 7: -1.0, 2: 1.0} and got["NEC10 0.9D-E10"] == {1: 0.9, 10: -1.0}, got
    assert combos[-1].type == "SLS" and len(combos) == 11, [c.name for c in combos]
    ortho = writes.nec_combinations([1], [2], [], [], [7], [10], orthogonal=True, both_signs=False, service=False)
    assert [c.name for c in ortho][-2:] == ["NEC5 0.9D+E7+0.3E10", "NEC6 0.9D+E10+0.3E7"], [c.name for c in ortho]
    # la escala multiplica cada caso sísmico, también el 30 % ortogonal
    scaled = writes.nec_combinations([1], [2], [], [], [7], [10], seismic_scale_x=0.2, seismic_scale_y=0.25, orthogonal=True, both_signs=False, service=False)
    got = {c.name: {f.case: f.factor for f in c.factors} for c in scaled}
    assert got["NEC3 1.2D+E7+0.3E10+L"] == {1: 1.2, 7: 0.2, 10: 0.075, 2: 1.0}, got
    assert got["NEC6 0.9D+E10+0.3E7"] == {1: 0.9, 10: 0.25, 7: 0.06}, got
    try:
        writes.nec_combinations([1], [1], [], [], [], [])
        raise AssertionError("un caso en dos categorías debía fallar")
    except ToolError:
        pass


def test_aci() -> None:
    # viga 30x50, d = 44 cm, f'c 28, fy 420, Mu 150 kN·m: As = 9.64 cm² (cálculo a mano)
    assert abs(design.beam_steel(150e6, 300, 440, 28, 420) - 964) < 2
    shear = design.shear_steel(150e3, 0, 300, 500, 440, 28, 420)  # Vc = 0.17·√28·300·440 = 118.7 kN
    assert abs(shear["vc"] - 118_741) < 50 and abs(shear["av_s"] - 0.4397) < 1e-3, shear
    curve = design.column_curve(400, 400, 60, 0.01, 3, 28, 420)
    # flexión pura, 8 barras en 40x40: equilibrio a mano c ≈ 56 mm, Mn ≈ 110 kN·m, φ = 0.9
    assert 95e6 < design.moment_capacity(curve, 0) < 104e6, design.moment_capacity(curve, 0)
    assert abs(curve[-1][1] - 0.52 * (0.85 * 28 * (160_000 - 1600) + 420 * 1600)) < 1  # 0.65·0.80·Po
    rho = design.required_rho([(2.6e6, 0, 0)], 400, 400, 60, 3, 28, 420)  # 0.52·Po = 2600 kN -> ρ = 1.880 %
    assert rho and abs(rho - 0.0188) < 2e-4, rho
    assert design.required_rho([(9e6, 0, 0)], 400, 400, 60, 3, 28, 420) is None


